"""Account-scoped bundle and expectation lifecycle; callers own transactions."""

from datetime import UTC, datetime
from typing import Any, Literal, cast
from uuid import UUID, uuid4

from sqlalchemy import func, select, update
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.orm import Session
from sqlalchemy.engine import CursorResult

from preloop.models import models
from preloop.schemas.managed_bundle import BundleManifest, ControlExpectationInput

from .expected_device import crud_expected_device


class CRUDBundleRevision:
    """Serialize registration and generation with the account's evidence lock."""

    def register(
        self,
        db: Session,
        *,
        account_id: UUID,
        manifest: BundleManifest,
        user_id: UUID | None = None,
    ) -> models.RegisteredBundleRevision:
        """Register idempotently, retiring the prior scope and generated rows.

        A replay of a retired revision is rejected, so delayed registrations
        cannot silently roll policy back. Metadata for a revision is immutable.
        No expectations are generated by registration itself.
        """
        manifest = BundleManifest.model_validate(manifest)
        crud_expected_device.lock_account(db, account_id=account_id)
        model = models.RegisteredBundleRevision
        scope = (
            model.account_id == account_id,
            model.app_id == manifest.app_id,
            model.platform == manifest.platform,
        )
        existing = db.scalar(
            select(model).where(
                *scope, model.policy_revision_hash == manifest.policy_revision_hash
            )
        )
        metadata = manifest.model_dump(mode="json", by_alias=True)
        if existing is not None:
            if existing.retired_at is not None:
                raise ValueError("Bundle revision is retired")
            if existing.manifest != metadata:
                raise ValueError("Registered revision metadata is immutable")
            return existing
        now = datetime.now(UTC)
        previous = db.scalar(select(model).where(*scope, model.retired_at.is_(None)))
        if previous is not None:
            previous.retired_at = now
            db.execute(
                update(models.ControlExpectation)
                .where(
                    models.ControlExpectation.account_id == account_id,
                    models.ControlExpectation.bundle_revision_id == previous.id,
                    models.ControlExpectation.origin == "bundle",
                    models.ControlExpectation.retired_at.is_(None),
                )
                .values(retired_at=now)
            )
            db.flush()
        row = model(
            account_id=account_id,
            app_id=manifest.app_id,
            platform=manifest.platform,
            policy_revision_hash=manifest.policy_revision_hash,
            manifest=metadata,
            registered_at=now,
        )
        db.add(row)
        db.flush()
        from . import crud_audit_log

        crud_audit_log.log_action(
            db,
            account_id=account_id,
            action="configuration_change",
            user_id=user_id,
            resource_type="registered_bundle_revision",
            resource_id=str(row.id),
            status="success",
            details={
                "config_type": "managed_bundle",
                "app_id": row.app_id,
                "platform": row.platform,
                "policy_revision_hash": row.policy_revision_hash,
            },
            commit=False,
        )
        return row

    def list_active(
        self, db: Session, *, account_id: UUID
    ) -> list[models.RegisteredBundleRevision]:
        """Return current bundles only for the selected account."""
        model = models.RegisteredBundleRevision
        return list(
            db.scalars(
                select(model)
                .where(model.account_id == account_id, model.retired_at.is_(None))
                .order_by(model.app_id, model.platform)
            )
        )


class CRUDControlExpectation:
    """Store tuple identities without replacing the manual settings document."""

    def upsert(
        self,
        db: Session,
        *,
        account_id: UUID,
        expectation: ControlExpectationInput,
        origin: Literal["bundle", "manual"],
        bundle_revision_id: UUID | None = None,
    ) -> models.ControlExpectation:
        """Upsert one origin's tuple, validating bundle and evidence eligibility.

        Bundle rows require the active registered revision and a persisted
        report from this account/source/workstation listing the same app,
        platform and config context. User enrollment alone never qualifies.
        Retired tuples can be revived only while their bundle remains current.
        """
        expectation = ControlExpectationInput.model_validate(expectation)
        if origin not in {"bundle", "manual"} or (
            origin == "manual" and bundle_revision_id is not None
        ):
            raise ValueError("Invalid expectation origin or bundle reference")
        crud_expected_device.lock_account(db, account_id=account_id)
        if origin == "bundle":
            bundle = db.scalar(
                select(models.RegisteredBundleRevision).where(
                    models.RegisteredBundleRevision.account_id == account_id,
                    models.RegisteredBundleRevision.id == bundle_revision_id,
                    models.RegisteredBundleRevision.retired_at.is_(None),
                )
            )
            if (
                bundle is None
                or bundle.policy_revision_hash != expectation.policy_revision_hash
                or {"claude-code": "claude_code"}.get(bundle.app_id)
                != expectation.agent_kind
            ):
                raise ValueError(
                    "An active registered bundle matching the app and revision is required"
                )
            # This bundle currently declares only the managed native tool hook.
            if (
                expectation.axis != "native_tool_hook"
                or expectation.required_scope != "managed_config"
            ):
                raise ValueError("Expectation axis/scope is not declared by the bundle")
            evidence = models.DiscoveryObservation
            report = db.scalar(
                select(evidence.id)
                .where(
                    evidence.account_id == account_id,
                    evidence.source_ref == expectation.source_ref,
                    evidence.workstation_fingerprint
                    == expectation.workstation_fingerprint,
                    evidence.evidence["os_family"].astext == bundle.platform,
                    evidence.evidence["applications"].contains(
                        [
                            {
                                "agent_kind": expectation.agent_kind,
                                "config_path_hash": expectation.config_path_hash,
                            }
                        ]
                    ),
                )
                .limit(1)
            )
            if report is None:
                raise ValueError("Matching application/platform evidence is required")
        model = models.ControlExpectation
        values = expectation.model_dump()
        statement = insert(model).values(
            id=uuid4(),
            account_id=account_id,
            origin=origin,
            bundle_revision_id=bundle_revision_id,
            retired_at=None,
            **values,
        )
        row = db.scalar(
            statement.on_conflict_do_update(
                constraint="uq_control_expectation_tuple",
                set_={
                    "required_scope": expectation.required_scope,
                    "bundle_revision_id": bundle_revision_id,
                    "retired_at": None,
                    "updated_at": func.now(),
                },
            )
            .returning(model)
            .execution_options(populate_existing=True)
        )
        assert row is not None
        return row

    def list_active(
        self,
        db: Session,
        *,
        account_id: UUID,
        origin: Literal["bundle", "manual"] | None = None,
    ) -> list[models.ControlExpectation]:
        """Read active tuples for the evaluator, independently of settings PUTs."""
        model = models.ControlExpectation
        query = select(model).where(
            model.account_id == account_id, model.retired_at.is_(None)
        )
        if origin is not None:
            query = query.where(model.origin == origin)
        return list(db.scalars(query.order_by(model.id)))

    def generated_count(
        self, db: Session, *, account_id: UUID, bundle_revision_id: UUID | None = None
    ) -> int:
        """Count all active bundle rows in SQL, without a display cap."""
        model = models.ControlExpectation
        query = (
            select(func.count())
            .select_from(model)
            .where(
                model.account_id == account_id,
                model.origin == "bundle",
                model.retired_at.is_(None),
            )
        )
        if bundle_revision_id is not None:
            query = query.where(model.bundle_revision_id == bundle_revision_id)
        return db.scalar(query) or 0

    def retire_bundle_scope(
        self,
        db: Session,
        *,
        account_id: UUID,
        source_ref: UUID,
        workstation_fingerprint: str,
        agent_kind: str,
        config_path_hash: str,
    ) -> int:
        """Retire generated rows for a removed evidence context; preserve manual."""
        crud_expected_device.lock_account(db, account_id=account_id)
        model = models.ControlExpectation
        result = db.execute(
            update(model)
            .where(
                model.account_id == account_id,
                model.source_ref == source_ref,
                model.workstation_fingerprint == workstation_fingerprint,
                model.agent_kind == agent_kind,
                model.config_path_hash == config_path_hash,
                model.origin == "bundle",
                model.retired_at.is_(None),
            )
            .values(retired_at=datetime.now(UTC))
        )
        return int(cast(CursorResult[Any], result).rowcount)


crud_bundle_revision = CRUDBundleRevision()
crud_control_expectation = CRUDControlExpectation()
