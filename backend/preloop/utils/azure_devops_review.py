"""Public attribution and stable summary markers for Azure Repos reviews."""

import re
from dataclasses import dataclass, field
from difflib import SequenceMatcher
from typing import Any

GENERATED_BY = "Generated by Preloop"
SUMMARY_MARKER = "<!-- preloop-review:summary -->"


def generated_body(body: str) -> str:
    """Label a comment while retaining its hidden review markers."""
    if body.startswith(GENERATED_BY + "\n") or body == GENERATED_BY:
        return body
    return f"{GENERATED_BY}\n\n{body}"


def is_review_summary(body: str) -> bool:
    """Recognize summaries without relying on the PAT owner's display name."""
    return SUMMARY_MARKER in body or (
        bool(re.search(r"<!--\s*preloop-review:flow-id:[^\s:>]+\s*-->", body))
        and any(
            title in body for title in ("Preloop Code Review", "Preloop Review Summary")
        )
    )


def reviewed_sha(body: str) -> str | None:
    """Read the immutable reviewed commit from the reviewer's hidden marker."""
    match = re.search(
        r"<!--\s*preloop-review:reviewed-sha:([0-9a-fA-F]{40})\s*-->", body
    )
    return match.group(1).lower() if match else None


@dataclass
class ReviewPositionCache:
    """Immutable Azure diff metadata retained only for one review publication."""

    iterations: dict[str, list[dict[str, Any]]] = field(default_factory=dict)
    changes: dict[tuple[str, int], list[dict[str, Any]]] = field(default_factory=dict)
    ranges: dict[tuple[str, int, str], tuple[tuple[int, int], ...]] = field(
        default_factory=dict
    )


def changed_line_ranges(
    before: list[str], after: list[str]
) -> tuple[tuple[int, int], ...]:
    """Return changed right-side line ranges as exclusive-start/inclusive-end pairs."""
    return tuple(
        (start, end)
        for tag, _, _, start, end in SequenceMatcher(
            None, before, after, autojunk=False
        ).get_opcodes()
        if tag in ("insert", "replace")
    )
