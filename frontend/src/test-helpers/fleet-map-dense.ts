const AGO = /^__AGO_(\d+)__$/;

function rebase<T>(value: T, now: number): T {
  if (typeof value === 'string') {
    const match = AGO.exec(value);
    return (
      match ? new Date(now - Number(match[1]) * 60_000).toISOString() : value
    ) as T;
  }
  if (Array.isArray(value))
    return value.map((item) => rebase(item, now)) as unknown as T;
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, rebase(item, now)])
    ) as T;
  return value;
}

